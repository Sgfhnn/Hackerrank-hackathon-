"""Writes ../sample_explanations.md: for every gold step of the 32 samples, how our engine links the
resource to the case (via), which evidence/activity explains its state, and whether we reproduce it."""
import csv, json, os
from engine import Engine, DATASET, parse_ts

eng = Engine()
allc = list(csv.DictReader(open(os.path.join(DATASET, "sample_deletion_requests.csv")))) + \
    list(csv.DictReader(open(os.path.join(DATASET, "deletion_requests.csv"))))
eng.prepare(allc)
C = {c["case_id"]: c for c in allc}
gold = {r["case_id"]: (r["deletion_status"], json.loads(r["steps_json"])) for r in csv.DictReader(open(os.path.join(DATASET, "sample_output.csv")))}
out = ["# Sample step explanations (auto-generated by code/explain_samples.py)\n",
       "Columns: step | gold op | resource | gold evidence | how linked (engine) | engine state | supporting activities (<= audit_at)\n"]
for cid in sorted(gold, key=lambda c: int(c.split("_")[1])):
    gs, steps = gold[cid]
    c = C[cid]
    ps, psteps, dbg = eng.plan(c)
    ok = [(s["operation"], s["resource_id"], s["evidence_id"]) for s in steps] == [(s["operation"], s["resource_id"], s["evidence_id"]) for s in psteps]
    out.append(f"\n## {cid} gold={gs} pred={ps} {'EXACT' if ok and gs == ps else 'DIFF'}\n")
    out.append(f"email={c['email']} user={eng.case_user.get(cid)} requested={c['requested_at']} reported={c['reported_at']} ({c['reported_status']}) audit={c['audit_at']}\n")
    out.append(f"text: {c['request_text'][:220]}\n\n")
    out.append("| # | op | resource | gold ev | linked via | engine state | activities |\n|---|---|---|---|---|---|---|\n")
    audit = parse_ts(c["audit_at"])
    for s in steps:
        rid = s["resource_id"]
        d = dbg.get(rid, {})
        acts = "; ".join(f"{a['activity_id']} {a['event_type']} {a['reported_result']}" for a in eng.act_by_rid.get(rid, []) if a["ts"] <= audit)
        stt = "" if not d else f"tr={d['tr']} present={d['present']} pii={d['pii']} en={d['enabled']} restore={d['restore']} ev={d['ev']}"
        out.append(f"| {s['step_no']} | {s['operation']} | {s['system_id']}/{rid} | {s['evidence_id']} | {','.join(d.get('via', ['NOT FOUND']))} | {stt} | {acts} |\n")
open(os.path.join(os.path.dirname(__file__), "sample_explanations.md"), "w").write("".join(out))
print("ok")
